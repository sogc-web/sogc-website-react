export function getEventCatalog(eventsSection, lang) {
  const baseEvents = [eventsSection.featured, ...(eventsSection.items ?? [])]
  const localizedDetails = eventDetails[lang] ?? eventDetails.en

  return baseEvents.map((event, index) => ({
    ...event,
    ...localizedDetails[index],
    registrationUrl: '',
  }))
}
